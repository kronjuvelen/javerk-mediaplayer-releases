const fs = require('node:fs');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { verifyManifest } = require('./update-signature.cjs');
const spec = require('../release-input/release.json');
const gh = (...args) => execFileSync('gh', args, { encoding: 'utf8' });
const tag = `v${spec.version}`;
const info = JSON.parse(fs.readFileSync(`approved/${spec.version}.yml`, 'utf8'));
verifyManifest(info, spec.publicKey, spec.publish.owner, spec.publish.repo);
if (info.version !== spec.version) throw new Error('Wrong approved release version');
const release = JSON.parse(gh('release', 'view', tag, '--json', 'isDraft'));
if (!release.isDraft) throw new Error('This release is already public. Use a newer version.');
gh('release', 'download', tag, '--pattern', info.path, '--dir', 'verification');
const installer = fs.readFileSync(`verification/${info.path}`);
if (installer.length !== info.files[0].size || crypto.createHash('sha512').update(installer).digest('base64') !== info.sha512) throw new Error('Draft installer does not match the approved signature');
fs.mkdirSync('approved-release', { recursive: true });
fs.writeFileSync('approved-release/latest.yml', JSON.stringify(info, null, 2) + '\n');
gh('release', 'upload', tag, 'approved-release/latest.yml', '--clobber');
gh('release', 'edit', tag, '--draft=false', '--latest');
console.log(`PUBLISHED https://github.com/${process.env.GH_REPO}/releases/tag/${tag}`);
